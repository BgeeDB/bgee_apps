public class TopAnatRManager {

    private final static Logger log = LogManager.getLogger(TopAnatRManager.class.getName());

    /**
     * A {@code String} that is the prefix of the message printed in the R console 
     * when an analysis produces no result and an empty result file is created. 
     * Because RCaller throws an exception when a result file is empty 
     * (with a message matching the regex "^.*?Can not parse output: The generated file .+? is empty.*$"), 
     * and because it also throws this exception for some real types of errors, 
     * we use this message to formally check whether the exception was caused by an absence of results.
     */
    public static final String NO_RESULT_MESSAGE_PREFIX = "No result, creating an empty result file";

    private final RCaller caller;

    private final RCode code;

    private final BgeeProperties props;

    private final TopAnatParams params;

    /**
     * 
     * @param props
     * @param topAnatParams
     */
    public TopAnatRManager(BgeeProperties props, TopAnatParams topAnatParams){
        log.entry(props, topAnatParams);
        Globals.setRscriptCurrent(props.getTopAnatRScriptExecutable());
        //A failing analysis is run again once, not more, an analysis can take long
        this.caller = RCaller.create(RCallerOptions.create(FailurePolicy.RETRY_1, Long.MAX_VALUE));
        this.code = RCode.create();
        this.props = props;
        this.params = topAnatParams;
        log.traceExit();
    }

    /**
     * 
     * @param caller
     * @param code
     * @param props
     * @param params
     */
    public TopAnatRManager(RCaller caller, RCode code, BgeeProperties props, TopAnatParams params){

        log.entry(caller,code,props,params);
        Globals.setRscriptCurrent(props.getTopAnatRScriptExecutable());
        this.caller = caller;
        this.code = code;
        this.props = props;
        this.params = params;
        log.traceExit();
    }

    /**
     * Generates the R code of the analysis run on the server: BgeeDB reads the conditions and
     * their relations generated by {@code TopAnatService}, the expression calls and the background
     * written by {@code TopAnatAnalysis}, runs the test, and writes the table of the results, and
     * the graph of the most significant conditions. The code is then run by
     * {@link #performRFunction(String)}.
     *
     * @param resultFilePath            A {@code String} that is the path to the directory of
     *                                  the analysis, the working directory of the R code.
     * @param resultFileName            A {@code String} that is the name of the file of
     *                                  the results to write.
     * @param resultPdfFileName         A {@code String} that is the name of the PDF file of
     *                                  the graph to write.
     * @param conditionFile             A {@code Path} that is the file of the conditions and
     *                                  their names.
     * @param conditionRelationFile     A {@code Path} that is the file of the relations between
     *                                  the conditions.
     * @param geneToConditionsFile      A {@code Path} that is the file of the genes and
     *                                  the conditions they are expressed in.
     * @param backgroundFile            A {@code Path} that is the file of the IDs of the genes of
     *                                  the background.
     * @param foregroundIds             A {@code Set} of {@code String}s that are the IDs of
     *                                  the genes of interest.
     * @return                          A {@code String} that is the R code generated.
     */
    protected String generateRCode(String resultFilePath, 
            String resultFileName, String resultPdfFileName, 
            Path conditionFile, Path conditionRelationFile, Path geneToConditionsFile,
            Path backgroundFile, Set<String> foregroundIds) {
        log.traceEntry("{}, {}, {}, {}, {}, {}, {}, {}", resultFilePath, resultFileName,
                resultPdfFileName, conditionFile, conditionRelationFile,
                geneToConditionsFile, backgroundFile, foregroundIds);

        String bioconductorRelease = this.props.getBioconductorReleaseNumber();
        String minimumVersion = this.props.getBgeeDBMinimumVersion();

        code.clear();
        code.addRCode("# The packages, installed when missing: BgeeDB of the Bioconductor release "
                + bioconductorRelease + ", at least its version " + minimumVersion);
        code.addRCode("if (!nzchar(system.file(package = 'BiocManager'))) {");
        code.addRCode("  install.packages('BiocManager', repos = 'https://cloud.r-project.org')");
        code.addRCode("}");
        code.addRCode("if (!nzchar(system.file(package = 'BgeeDB')) || packageVersion('BgeeDB') < '"
                + minimumVersion + "') {");
        code.addRCode("  BiocManager::install('BgeeDB', version = '" + bioconductorRelease
                + "', update = FALSE, ask = FALSE)");
        code.addRCode("}");
        code.addRCode("library(BgeeDB)");
        code.addRCode("if (packageVersion('BgeeDB') < '" + minimumVersion + "') {");
        code.addRCode("  stop('BgeeDB " + minimumVersion + " or later is needed, version ', "
                + "as.character(packageVersion('BgeeDB')), ' is installed')");
        code.addRCode("}");
        //Rgraphviz draws the graph. RCaller needs no package, it provides its own R code.
        code.addRCode("if (!nzchar(system.file(package = 'Rgraphviz'))) {");
        code.addRCode("  BiocManager::install('Rgraphviz', version = '" + bioconductorRelease
                + "', update = FALSE, ask = FALSE)");
        code.addRCode("}");
        //The versions of R and of the packages, in the console log given to the user, before
        //its last line, which tells an analysis without result. Rgraphviz is only loaded to draw
        //the graph.
        code.addRCode("print(sessionInfo())");
        code.addRCode("cat('Rgraphviz', as.character(packageVersion('Rgraphviz')), '\\n')");

        code.addRCode("setwd('" + resultFilePath + "')");
        code.addRCode("resultExist <- FALSE");
        code.addStringArray("topOBOResultFile", new String[] {resultFileName});
        code.addStringArray("resultPDF", new String[] {resultPdfFileName});
        code.addStringArray("geneToConditionsFile", new String[] {geneToConditionsFile.toString()});
        code.addStringArray("foregroundGenes", new TreeSet<>(foregroundIds).toArray(new String[0]));

        //maybe there is no expression call with the parameters of the analysis,
        //for instance at a stage without data
        code.addRCode("if (nrow(data.table::fread(geneToConditionsFile, nrows = 1)) > 0) {");
        code.addRCode("  topAnatData <- BgeeDB:::loadTopAnatDataFromFiles(geneToConditionsFile, '"
                + conditionFile + "', '" + conditionRelationFile + "', '"
                + this.params.getCallFileType().getStringRepresentation() + "')");
        code.addRCode("  background <- read.table('" + backgroundFile
                + "', header = TRUE, sep = '\\t', colClasses = 'character')$GENE_ID");
        //maybe no gene of interest has data, or there are fewer genes with data
        //in the background than the threshold on node size
        code.addRCode("  universe <- intersect(names(topAnatData$gene2anatomy), background)");
        code.addRCode("  if (any(foregroundGenes %in% universe) && length(universe) >= "
                + this.params.getNodeSize() + ") {");
        code.addRCode("    myTopAnatObject <- topAnat(topAnatData, foregroundGenes = foregroundGenes, "
                + "background = background, nodeSize = " + this.params.getNodeSize() + ")");
        code.addRCode("    results <- runTest(myTopAnatObject, algorithm = '"
                + this.params.getDecorrelationType().getCode() + "', statistic = '"
                + this.params.getStatisticTest().getCode() + "')");
        //The conditions redundant with a more precise one are kept in the result file, flagged:
        //the analyses being cached by their parameters, a display can show them without running
        //the analysis again
        code.addRCode("    tableOver <- makeTable(topAnatData, myTopAnatObject, results, cutoff = "
                + this.params.getFdrThreshold() + ", keepRedundant = TRUE)");
        //if we get results, save the results and generate a graph visualization
        code.addRCode("    if (is.data.frame(tableOver) && nrow(tableOver) > 0) {");
        //The columns read by the web page, with 3 significant digits
        code.addRCode("      for (column in c('expected', 'foldEnrichment', 'pValue', 'FDR')) {");
        code.addRCode("        tableOver[[column]] <- signif(tableOver[[column]], 3)");
        code.addRCode("      }");
        code.addRCode("      names(tableOver) <- c('OrganId', 'OrganName', 'Annotated', 'Significant', "
                + "'Expected', 'foldEnrichment', 'p', 'fdr', '" + TopAnatResults.REDUNDANT_COLUMN + "')");
        code.addRCode("      write.table(tableOver, file = topOBOResultFile, sep = '\\t', row.names = FALSE, "
                + "col.names = TRUE, quote = FALSE)");
        code.addRCode("      resultExist <- TRUE");
        //the most significant conditions below the p-value threshold, at most
        //the number of nodes requested, without the redundant ones, as the graph draws them
        code.addRCode("      resultCount <- min(sum(tableOver$p <= " + this.params.getPvalueThreshold()
                + " & !tableOver$" + TopAnatResults.REDUNDANT_COLUMN + "), "
                + this.params.getNumberOfSignificantNodes() + ")");
        code.addRCode("      cat(paste('Number of nodes to display: ', resultCount, '\\n'))");
        code.addRCode("      if (resultCount > 0) {");
        code.addRCode("        printTopAnatGraph(topAnatData, myTopAnatObject, results, "
                + "firstSigNodes = resultCount, fileName = resultPDF)");
        code.addRCode("      }");
        code.addRCode("    }");
        code.addRCode("  }");
        code.addRCode("}");

        //if there is no result, but no error occurred, we create an empty result file
        code.addRCode("if (!resultExist) {");
        code.addRCode("  cat('" + NO_RESULT_MESSAGE_PREFIX + ": ', topOBOResultFile, '\\n')");
        //invisible, so that the message stays the last line of the console
        code.addRCode("  invisible(file.create(topOBOResultFile))");
        code.addRCode("}");

        return log.traceExit(code.toString());
    }

    /**
     * Generates the script of the analysis given to the user: BgeeDB downloads from Bgee
     * the expression calls of the analysis, the same that the server reads in its files,
     * and runs the same test, so that the user can run the analysis again, or change it.
     *
     * @param backgroundFileName    A {@code String} that is the name of the file of the background
     *                              gene IDs submitted, given to the user next to the script,
     *                              {@code null} for a background of Bgee, downloaded by BgeeDB.
     * @return                      A {@code String} that is the R script generated.
     */
    protected String generateUserScript(String backgroundFileName) {
        log.traceEntry("{}", backgroundFileName);

        String release = TopAnatUtils.bgeeRelease(this.props);
        StringBuilder script = new StringBuilder();
        script.append("# The topAnat analysis of the Bgee web page, to run again with the BgeeDB R package\n")
              .append("# from Bioconductor, which downloads the expression calls from Bgee ").append(release)
              .append(".\n")
              .append("if (!requireNamespace('BiocManager', quietly = TRUE)) {\n")
              .append("  install.packages('BiocManager')\n")
              .append("}\n")
              .append("if (!requireNamespace('BgeeDB', quietly = TRUE) || packageVersion('BgeeDB') < '")
              .append(this.props.getBgeeDBMinimumVersion()).append("') {\n")
              .append("  BiocManager::install('BgeeDB')\n")
              .append("}\n")
              .append("# Rgraphviz draws the graph of the results\n")
              .append("if (!requireNamespace('Rgraphviz', quietly = TRUE)) {\n")
              .append("  BiocManager::install('Rgraphviz')\n")
              .append("}\n")
              .append("library(BgeeDB)\n\n");

        //The data types of the analysis, every data type of the release when all are requested.
        //BgeeDB distinguishes the two kinds of single-cell RNA-Seq, that the analyses combine.
        script.append("bgee <- Bgee$new(species = '").append(this.params.getSpeciesId())
              .append("', release = '").append(release).append("'");
        if (!this.params.getDataTypeCombination().equals(EnumSet.allOf(DataType.class))) {
            script.append(", dataType = c(").append(this.params.getDataTypeCombination().stream()
                    .flatMap(dataType -> {
                        switch (dataType) {
                        case IN_SITU:
                            return Stream.of("'in_situ'");
                        case RNA_SEQ:
                            return Stream.of("'rna_seq'");
                        case SC_RNA_SEQ:
                            return Stream.of("'sc_full_length'", "'sc_droplet_based'");
                        default:
                            throw log.throwing(new IllegalStateException(
                                    "Unsupported data type: " + dataType));
                        }
                    })
                    .collect(Collectors.joining(", "))).append(")");
        }
        script.append(")\n");
        script.append("myTopAnatData <- loadTopAnatData(bgee");
        if (StringUtils.isNotBlank(this.params.getDevStageId())) {
            script.append(", stage = '").append(this.params.getDevStageId()).append("'");
        }
        script.append(", confidence = '")
              .append(SummaryQuality.GOLD.equals(this.params.getSummaryQuality()) ? "gold" : "silver")
              .append("', callFileType = '")
              .append(this.params.getCallFileType().getStringRepresentation()).append("')\n");

        script.append("foregroundGenes <- c(");
        List<String> foregroundIds = new ArrayList<>(new TreeSet<>(this.params.getSubmittedForegroundIds()));
        for (int i = 0; i < foregroundIds.size(); i++) {
            script.append(i % 5 == 0 ? "\n  " : " ").append("'").append(foregroundIds.get(i)).append("'")
                  .append(i < foregroundIds.size() - 1 ? "," : "");
        }
        script.append(")\n");
        if (backgroundFileName != null) {
            script.append("# The background gene IDs submitted, in the file next to this script\n")
                  .append("background <- read.table('").append(backgroundFileName)
                  .append("', header = TRUE, sep = '\\t', colClasses = 'character')$GENE_ID\n");
        } else {
            script.append("background <- '").append(this.params.getBackground().getStringRepresentation())
                  .append("'\n");
        }
        script.append("myTopAnatObject <- topAnat(myTopAnatData, foregroundGenes = foregroundGenes, ")
              .append("background = background, nodeSize = ").append(this.params.getNodeSize()).append(")\n")
              .append("results <- runTest(myTopAnatObject, algorithm = '")
              .append(this.params.getDecorrelationType().getCode()).append("', statistic = '")
              .append(this.params.getStatisticTest().getCode()).append("')\n")
              .append("# Without the conditions redundant with a more precise one: keepRedundant = TRUE ")
              .append("keeps them, flagged in a column redundant, as the results file does\n")
              .append("tableOver <- makeTable(myTopAnatData, myTopAnatObject, results, cutoff = ")
              .append(this.params.getFdrThreshold()).append(")\n")
              .append("# The graph of the most significant conditions below the p-value threshold, at most ")
              .append(this.params.getNumberOfSignificantNodes()).append("\n")
              .append("if (is.data.frame(tableOver)) {\n")
              .append("  resultCount <- min(sum(tableOver$pValue <= ").append(this.params.getPvalueThreshold())
              .append("), ").append(this.params.getNumberOfSignificantNodes()).append(")\n")
              .append("  if (resultCount > 0) {\n")
              .append("    printTopAnatGraph(myTopAnatData, myTopAnatObject, results, firstSigNodes = resultCount, ")
              .append("fileName = 'topAnat_graph.pdf')\n")
              .append("  }\n")
              .append("}\n");

        return log.traceExit(script.toString());
    }

    protected void performRFunction(String consoleFileName) throws FileNotFoundException {

        log.info("Running statistical tests in R...");
        if(this.code.toString().equals(RCode.create().toString())){
            throw new IllegalStateException("The R code was not set before the analysis");
        }
        caller.redirectROutputToFile(consoleFileName, true);
        caller.setRCode(code);
        //RCaller returns a variable by converting it into XML element by element, which takes
        //tens of seconds for the result table once topGO has attached BiocGenerics: the results
        //are read from the file written by the R code, the variable returned is only a flag.
        try {
            caller.runAndReturnResult("resultExist");
        } catch (RuntimeException e) {
            //When the thread is interrupted, for instance by the cancellation of its job, RCaller
            //stops waiting for R without stopping it, and R would run the analysis to its end.
            //Stopping R does nothing when it has already ended.
            caller.stopRCallerAsync();
            throw e;
        }
        log.traceExit();

    }

}
