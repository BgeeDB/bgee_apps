    private final static int SPECIES_ID = 6239;
    /**
     * The IDs of the conditions of the generated files, sorted: the index of a condition
     * in the call files is its position.
     */
    private final static List<String> CONDITION_IDS = List.of("UBERON:0000061", "UBERON:0000062",
            "UBERON:0000955");

    @Rule
    public TemporaryFolder tmpFolder = new TemporaryFolder();

    private BgeeProperties props;
    private ServiceFactory serviceFactory;
    private TopAnatService topAnatService;

    /**
     * Writes the files generated by {@code TopAnatService} that the analyses read: the propagated
     * calls of the species, for the combination of all data types only, the one used when
     * no data type is requested, the conditions, and the relations between them.
     */
    @Before
    public void writeGeneratedFiles() throws IOException {
        String root = this.tmpFolder.getRoot().getPath() + "/";
        Files.createDirectories(Paths.get(root, TopAnatService.CALL_FILE_DIRECTORY));
        TopAnatCallFile.CallFileWriter writer = new TopAnatCallFile.CallFileWriter(
                TopAnatService.getCallFilePath(root, CallFileType.PROPAGATED, SPECIES_ID),
                List.of(TopAnatService.combinationColumnName(EnumSet.allOf(DataType.class))),
                CONDITION_IDS);
        //At the root of the stages, G1 holds a GOLD call in the anatomical structure and
        //a SILVER call in the organ, G2 a SILVER call in the anatomical structure, G3 a SILVER
        //call in the brain. G4 only holds a call at another stage.
        writer.write(ConditionDAO.DEV_STAGE_ROOT_ID, "G1", "0:G,1:S");
        writer.write(ConditionDAO.DEV_STAGE_ROOT_ID, "G2", "0:S");
        writer.write(ConditionDAO.DEV_STAGE_ROOT_ID, "G3", "2:S");
        writer.write("UBERON:0000092", "G4", "1:S");
        writer.complete();
        Files.write(TopAnatService.getConditionFilePath(root, SPECIES_ID), List.of(
                "ID\tNAME\tANAT_ENTITY_ID\tCELL_TYPE_ID",
                "UBERON:0000061\tanatomical structure\tUBERON:0000061\tGO:0005575",
                "UBERON:0000062\torgan\tUBERON:0000062\tGO:0005575",
                "UBERON:0000955\tbrain\tUBERON:0000955\tGO:0005575"));
        Files.write(TopAnatService.getConditionRelationFilePath(root, SPECIES_ID), List.of(
                "SOURCE_ID\tTARGET_ID",
                "UBERON:0000062\tUBERON:0000061",
                "UBERON:0000955\tUBERON:0000062"));

        this.props = mock(BgeeProperties.class);
        when(this.props.getTopAnatResultsWritingDirectory()).thenReturn(root);
        when(this.props.getTopAnatRScriptExecutable()).thenReturn("Rscript");
        when(this.props.getMajorVersion()).thenReturn("16");
        when(this.props.getMinorVersion()).thenReturn("0");
        when(this.props.getBioconductorReleaseNumber()).thenReturn("3.24");
        when(this.props.getBgeeDBMinimumVersion()).thenReturn("2.39.4");
        //Every gene submitted belongs to the species
        GeneService geneService = mock(GeneService.class);
        when(geneService.loadGenes(any(GeneFilter.class))).thenAnswer(invocation ->
                invocation.<GeneFilter>getArgument(0).getGeneIds().stream()
                .map(id -> new Gene(id, new Species(SPECIES_ID), new GeneBioType("protein_coding"))));
        this.serviceFactory = mock(ServiceFactory.class);
        when(this.serviceFactory.getGeneService()).thenReturn(geneService);
        this.topAnatService = mock(TopAnatService.class);
        when(this.topAnatService.getReadWriteLocks()).thenReturn(new ManageReadWriteLocks());
        when(this.topAnatService.loadBackgroundGeneIds(SPECIES_ID, Background.PROTEIN_CODING))
                .thenReturn(List.of("G1", "G3"));
    }

    /**
     * Test the files written for R, and the files of the results of an analysis.
     */
    @Test
    public void shouldWriteTheFilesOfTheAnalysis() throws Exception {
        TopAnatParams params = new TopAnatParams.Builder(Set.of("G1"), SPECIES_ID,
                SummaryCallType.ExpressionSummary.EXPRESSED).build();
        List<String> readCalls = new ArrayList<>();
        List<String> readBackground = new ArrayList<>();
        TopAnatAnalysis analysis = this.analysis(params, (a, consoleFile) -> {
            readCalls.addAll(Files.readAllLines(a.getGeneToConditionsFile()));
            readBackground.addAll(Files.readAllLines(a.getBackgroundFile()));
            writeResults(a, consoleFile);
        });
        TopAnatResults results = analysis.proceedToAnalysis();

        //The SILVER and GOLD calls of the combination of all data types, at the root of the stages
        assertEquals("Incorrect calls read by R", List.of("GENE_ID\tCONDITION_ID",
                "G1\tUBERON:0000061", "G1\tUBERON:0000062", "G2\tUBERON:0000061",
                "G3\tUBERON:0000955"), readCalls);
        assertEquals("Incorrect background read by R, the protein coding genes by default",
                List.of("GENE_ID", "G1", "G3"), readBackground);
        //The files read by R are deleted once read, the results moved to their final path
        assertFalse("The calls read by R should be deleted",
                Files.exists(analysis.getGeneToConditionsFile()));
        assertFalse("The background read by R should be deleted",
                Files.exists(analysis.getBackgroundFile()));
        assertTrue("The results should be moved to their final path",
                Files.exists(Paths.get(analysis.getResultFilePath(false))));
        assertEquals("Incorrect result file", analysis.getResultFileName(false),
                results.getResultFileName());
        assertTrue("The analysis should be done", analysis.isAnalysisDone());

        //The zip holds the results, and the script of the user, which downloads the calls with
        //BgeeDB: neither the calls nor the background of Bgee
        assertEquals("Incorrect files of the zip", Set.of(analysis.getResultFileName(false),
                analysis.getResultPDFFileName(false), analysis.getRScriptConsoleFileName(),
                analysis.getParamsOutputFileName(false), analysis.getRScriptAnalysisFileName(false)),
                zipEntries(analysis));
        List<String> script = Files.readAllLines(
                Paths.get(analysis.getRScriptAnalysisFilePath(false)));
        assertTrue("The script should download the calls of the release",
                script.contains("bgee <- Bgee$new(species = '6239', release = '16.0')"));
        assertTrue("The script should use the background of the analysis",
                script.contains("background <- 'protein_coding'"));
        assertTrue("The parameters should tell the release",
                Files.readAllLines(Paths.get(analysis.getParamsOutputFilePath(false)))
                .contains("Bgee version:\t16.0"));
    }

    /**
     * Test that the background gene IDs submitted are the background read by R, and that
     * the zip holds them for the script of the user.
     */
    @Test
    public void shouldUseTheBackgroundGeneIdsSubmitted() throws Exception {
        TopAnatParams params = new TopAnatParams.Builder(Set.of("G1"), Set.of("G3", "G1", "G2"),
                SPECIES_ID, SummaryCallType.ExpressionSummary.EXPRESSED).nodeSize(1).build();
        List<String> readBackground = new ArrayList<>();
        TopAnatAnalysis analysis = this.analysis(params, (a, consoleFile) -> {
            readBackground.addAll(Files.readAllLines(a.getBackgroundFile()));
            writeResults(a, consoleFile);
        });
        analysis.proceedToAnalysis();

        List<String> background = List.of("GENE_ID", "G1", "G2", "G3");
        assertEquals("Incorrect background read by R", background, readBackground);
        try (ZipFile zip = new ZipFile(analysis.getZipFilePath(false));
                BufferedReader reader = new BufferedReader(new InputStreamReader(
                        zip.getInputStream(zip.getEntry("topAnat_Background.tsv")),
                        StandardCharsets.UTF_8))) {
            assertEquals("Incorrect background in the zip", background,
                    reader.lines().collect(Collectors.toList()));
        }
        assertTrue("The script should read the background of the zip",
                Files.readAllLines(Paths.get(analysis.getRScriptAnalysisFilePath(false)))
                .contains("background <- read.table('topAnat_Background.tsv', header = TRUE, "
                        + "sep = '\\t', colClasses = 'character')$GENE_ID"));
    }

    /**
     * Test that two identical analyses run at the same time run R once: the second one waits
     * for the results of the first one.
     */
    @Test
    public void shouldRunROnceForIdenticalAnalyses() throws Exception {
        TopAnatParams params = new TopAnatParams.Builder(Set.of("G1"), SPECIES_ID,
                SummaryCallType.ExpressionSummary.EXPRESSED).build();
        AtomicInteger rRuns = new AtomicInteger();
        List<Callable<TopAnatResults>> analyses = new ArrayList<>();
        for (int i = 0; i < 2; i++) {
            TopAnatAnalysis analysis = this.analysis(params, (a, consoleFile) -> {
                rRuns.incrementAndGet();
                //Long enough for the other analysis to wait for the results
                Thread.sleep(500);
                writeResults(a, consoleFile);
            });
            analyses.add(analysis::proceedToAnalysis);
        }
        ExecutorService executor = Executors.newFixedThreadPool(2);
        try {
            for (Future<TopAnatResults> results: executor.invokeAll(analyses)) {
                assertEquals("Incorrect results", "topAnat_results.tsv",
                        results.get().getResultFileName());
            }
        } finally {
            executor.shutdown();
        }
        assertEquals("R should run once", 1, rRuns.get());
    }

    /**
     * Test an analysis without result: R writes an empty result file, that RCaller cannot parse.
     */
    @Test
    public void shouldAcceptAnAnalysisWithoutResult() throws Exception {
        TopAnatParams params = new TopAnatParams.Builder(Set.of("G1"), SPECIES_ID,
                SummaryCallType.ExpressionSummary.EXPRESSED).build();
        TopAnatAnalysis analysis = this.analysis(params, (a, consoleFile) -> {
            Files.createFile(Paths.get(a.getResultFilePath(true)));
            Files.write(consoleFile, List.of(TopAnatRManager.NO_RESULT_MESSAGE_PREFIX + ": "
                    + a.getResultFileName(true)));
            throw new ParseException("Can not parse output: The generated file is empty");
        });
        analysis.proceedToAnalysis();

        Path resultFile = Paths.get(analysis.getResultFilePath(false));
        assertTrue("The empty result file should be moved to its final path",
                Files.exists(resultFile));
        assertEquals("The result file should be empty", 0, Files.size(resultFile));
        assertFalse("The calls read by R should be deleted",
                Files.exists(analysis.getGeneToConditionsFile()));
    }

    /**
     * Test that an error of R fails the analysis, which can be run again.
     */
    @Test
    public void shouldFailWhenRFails() throws Exception {
        TopAnatParams params = new TopAnatParams.Builder(Set.of("G1"), SPECIES_ID,
                SummaryCallType.ExpressionSummary.EXPRESSED).build();
        TopAnatAnalysis analysis = this.analysis(params, (a, consoleFile) -> {
            Files.write(consoleFile, List.of("Error: an error of R"));
            throw new ParseException("Can not parse output");
        });

        assertThrows("An error of R should fail the analysis", RAnalysisException.class,
                () -> analysis.proceedToAnalysis());
        assertFalse("No result file should be written",
                Files.exists(Paths.get(analysis.getResultFilePath(false))));
        assertFalse("The calls read by R should be deleted",
                Files.exists(analysis.getGeneToConditionsFile()));
        assertFalse("The analysis should not be done", analysis.isAnalysisDone());
    }

    /**
     * What R does when an analysis runs, given the analysis and the console file of R.
     */
    @FunctionalInterface
    private static interface RRun {
        void run(TopAnatAnalysis analysis, Path consoleFile) throws Exception;
    }

    /**
     * @param params    The {@code TopAnatParams} of the analysis.
     * @param r         The {@code RRun} doing what R does when the analysis runs R.
     * @return          A {@code TopAnatAnalysis} whose {@code TopAnatRManager} generates the R code,
     *                  but does not run R: it runs {@code r}.
     */
    private TopAnatAnalysis analysis(TopAnatParams params, RRun r) throws IOException {
        TopAnatRManager rManager = spy(new TopAnatRManager(this.props, params));
        TopAnatAnalysis analysis = new TopAnatAnalysis(params, this.props, this.serviceFactory,
                rManager, this.topAnatService);
        doAnswer(invocation -> {
            r.run(analysis, Paths.get(invocation.<String>getArgument(0)));
            return null;
        }).when(rManager).performRFunction(anyString());
        return analysis;
    }

    /**
     * Writes the files that R writes for an analysis with results.
     */
    private static void writeResults(TopAnatAnalysis analysis, Path consoleFile)
            throws IOException {
        Files.write(Paths.get(analysis.getResultFilePath(true)), List.of(
                "OrganId\tOrganName\tAnnotated\tSignificant\tExpected\tfoldEnrichment\tp\tfdr",
                "UBERON:0000955\tbrain\t1\t1\t0.5\t2\t0.5\t0.5"));
        Files.write(Paths.get(analysis.getResultPDFFilePath(true)), List.of("PDF"));
        Files.write(consoleFile, List.of("Number of nodes to display:  1"));
    }

    /**
     * @return  The names of the entries of the zip file of {@code analysis}.
     */
    private static Set<String> zipEntries(TopAnatAnalysis analysis) throws IOException {
        try (ZipFile zip = new ZipFile(analysis.getZipFilePath(false))) {
            return Collections.list(zip.entries()).stream()
                    .map(entry -> entry.getName())
                    .collect(Collectors.toSet());
        }
    }
